func TestConvconvtranspose2d(t *testing.T) {
	evaluator, params, ecd, enc, dec := Conv_conv_transpose2d__configure()

	arg0 := make([]float32, 32)
	for i := range arg0 {
		arg0[i] = float32((i*5)%11-5) / 5
	}

	ct0 := Conv_conv_transpose2d__encrypt__arg0(evaluator, params, ecd, enc, arg0)
	resultCt := Conv_conv_transpose2d(evaluator, params, ecd, ct0)
	result := Conv_conv_transpose2d__decrypt__result0(evaluator, params, ecd, dec, resultCt)

	if len(result) != len(expected) {
		t.Fatalf("got %d outputs, expected %d", len(result), len(expected))
	}
	for i := range expected {
		if math.Abs(float64(result[i])-expected[i]) > 0.01 {
			t.Errorf("index %d: got %.4f, expected %.4f", i, result[i], expected[i])
		}
	}
}
